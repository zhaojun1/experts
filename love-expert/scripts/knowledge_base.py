def find_answer(question: str) -> Optional[str]:
    """智能问答匹配"""
    q = question.lower()

    best_match = None
    best_score = 0

    for qa in QA_DATABASE:
        # 多关键词加权匹配
        score = 0
        for kw in qa["keywords"]:
            if kw in q:
                score += 1
        # 标题匹配更高分
        if qa["question"] in q[:20]:
            score += 3

        if score > best_score:
            best_score = score
            best_match = qa

    if best_match and best_score >= 1:
        return f"## {best_match['question']}\n{best_match['answer']}"
    return None


def find_phenomenon(text: str) -> Optional[str]:
    """现象诊断匹配+分层方案输出"""
    for key, data in PHENOMENA.items():
        if any(kw in text for kw in data["关键词"]):
            result = f"## 🔍 {data['现象']}\n\n"
            result += "### 📋 可能原因\n"
            for i, d in enumerate(data["诊断"], 1):
                result += f"{i}. {d}\n"
            result += "\n### 🚨 紧急措施（24小时内）\n"
            for s in data["紧急措施"]:
                result += f"- {s}\n"
            result += "\n### 📅 中期方案（1-2周）\n"
            for s in data["中期方案"]:
                result += f"- {s}\n"
            if "长期建议" in data:
                result += "\n### 🔭 长期建议\n"
                for s in data["长期建议"]:
                    result += f"- {s}\n"
            result += f"\n### ⛔ 红线（绝对不能做）\n"
            for r in data["红线"]:
                result += f"- ❌ {r}\n"
            result += f"\n> 💡 **金句**：{data['金句']}"
            return result
    return None


def get_methodology(topic: str = "") -> str:
    """获取方法论内容"""
    if topic:
        t = topic.lower()
        for key, data in METHODOLOGY.items():
            if any(kw in t for kw in [key, data["title"]]):
                result = f"## 📚 {data['title']}\n\n"
                result += f"**核心**：{data['summary']}\n\n"
                if "原理" in data:
                    result += f"**原理**：\n{data['原理']}\n\n"
                if "案例" in data:
                    result += f"**案例**：\n{data['案例']}\n\n"
                if "要点" in data:
                    result += "**实操要点**：\n"
                    for i, t in enumerate(data["要点"], 1):
                        result += f"{i}. {t}\n"
                return result

    # 返回总览
    result = "## 📚 方法论总览\n\n"
    for key, data in METHODOLOGY.items():
        result += f"### {data['title']}\n{data['summary']}\n"
        if "要点" in data:
            result += f"— *{len(data['要点'])}条实操要点*\n"
        result += "\n"
    return result


